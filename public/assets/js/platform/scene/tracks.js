// Путь — прямая вдоль оси z на расстоянии x от камеры. Поезда ставятся на путь по имени,
// объекты сцены (балласт, рельсы, контактная сеть) строятся по его оси.
//
//   tracks: {
//     main:   { x: 4.42, platform: { side: -1, top: 1.1, edge: 2.5 } },  // у платформы слева от пути
//     second: { x: 9.7 },
//   }
//
// platform — описание платформы у пути (для света из окон поезда на платформу ночью):
//   side — с какой стороны платформа (−1 — со стороны меньших x), top — высота её пола над рельсом,
//   edge — x края платформы.
//
// Сейчас пути только прямые. Если понадобится кривая — достаточно добавить класс с теми же
// pointAt/heading и научить им поезд (trains/train.js): вагоны ставятся по точке и направлению пути.

export class Track {
  constructor(name, { x = 0, y = 0, from = 60, to = -3000, platform = null } = {}) {
    this.name = name;
    this.x = x;
    this.y = y;
    this.from = from;                 // ближний к камере конец (больший z)
    this.to = to;                     // дальний конец (к горизонту)
    this.platform = platform;
  }

  /** Точка на оси пути в координате z. */
  pointAt(z) {
    return [this.x, this.y, z];
  }

  /** Направление пути (единичный вектор к большим z). */
  heading() {
    return [0, 0, 1];
  }
}
